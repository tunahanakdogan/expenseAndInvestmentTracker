-- Fiyat ve kur geçmişi. Başka tablolara FK yok: (asset_type, symbol) ve currency ile anahtarlanır.
-- Birim fiyat ve kur 8 hane (fon fiyatları 6 hane); tutar kolonları ise NUMBER(19,4).
CREATE TABLE price_history (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_type VARCHAR2(20)  NOT NULL,
    symbol     VARCHAR2(30)  NOT NULL,
    price_date DATE          NOT NULL,
    price      NUMBER(19, 8) NOT NULL,
    currency   VARCHAR2(3)   NOT NULL,
    source     VARCHAR2(20)  NOT NULL,
    fetched_at TIMESTAMP     NOT NULL,
    CONSTRAINT uq_price_history UNIQUE (asset_type, symbol, price_date)
);

CREATE TABLE exchange_rate (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency   VARCHAR2(3)   NOT NULL,
    rate_date  DATE          NOT NULL,
    rate_try   NUMBER(19, 8) NOT NULL,
    source     VARCHAR2(20)  NOT NULL,
    fetched_at TIMESTAMP     NOT NULL,
    CONSTRAINT uq_exchange_rate UNIQUE (currency, rate_date)
);

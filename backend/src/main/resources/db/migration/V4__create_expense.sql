-- Harcama ve ödemeleri. Her harcama en az bir ödeme üretir; aylık liste ödemelerin dönemine (YYYY-MM) göredir.
CREATE TABLE expense (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           NUMBER        NOT NULL,
    account_id        NUMBER        NOT NULL,
    category_id       NUMBER        NOT NULL,
    description       VARCHAR2(200),
    expense_date      DATE          NOT NULL,
    total_amount      NUMBER(19, 4) NOT NULL,
    currency          VARCHAR2(3)   NOT NULL,
    installment_count NUMBER(3)     NOT NULL,
    created_at        TIMESTAMP     NOT NULL,
    CONSTRAINT fk_expense_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_expense_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_expense_category FOREIGN KEY (category_id) REFERENCES category (id)
);

CREATE INDEX ix_expense_account ON expense (account_id);
CREATE INDEX ix_expense_category ON expense (category_id);

CREATE TABLE expense_payment (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id     NUMBER        NOT NULL,
    installment_no NUMBER(3)     NOT NULL,
    period         VARCHAR2(7)   NOT NULL,
    amount         NUMBER(19, 4) NOT NULL,
    currency       VARCHAR2(3)   NOT NULL,
    status         VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT fk_expense_payment_expense FOREIGN KEY (expense_id) REFERENCES expense (id),
    CONSTRAINT uq_expense_payment_no UNIQUE (expense_id, installment_no)
);

CREATE INDEX ix_expense_payment_period ON expense_payment (period);

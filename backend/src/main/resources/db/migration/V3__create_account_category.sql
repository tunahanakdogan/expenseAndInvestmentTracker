-- Hesaplar (nakit, banka, kredi kartı) ve harcama kategorileri.
-- Kesim günü yalnız kredi kartında vardır ve orada zorunludur (D-001).
CREATE TABLE account (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       NUMBER       NOT NULL,
    name          VARCHAR2(60) NOT NULL,
    type          VARCHAR2(20) NOT NULL,
    currency      VARCHAR2(3)  NOT NULL,
    statement_day NUMBER(2),
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT fk_account_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT uq_account_user_name UNIQUE (user_id, name),
    CONSTRAINT ck_account_type CHECK (type IN ('CASH', 'BANK', 'CREDIT_CARD')),
    CONSTRAINT ck_account_currency CHECK (currency IN ('TRY', 'USD', 'EUR')),
    CONSTRAINT ck_account_statement_day CHECK (
        (type = 'CREDIT_CARD' AND statement_day BETWEEN 1 AND 31)
        OR (type <> 'CREDIT_CARD' AND statement_day IS NULL))
);

CREATE TABLE category (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER       NOT NULL,
    name       VARCHAR2(40) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_category_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT uq_category_user_name UNIQUE (user_id, name)
);

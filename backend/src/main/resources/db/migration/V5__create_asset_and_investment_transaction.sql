CREATE TABLE asset (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER        NOT NULL REFERENCES app_user (id),
    type       VARCHAR2(20)  NOT NULL,
    symbol     VARCHAR2(30)  NOT NULL,
    name       VARCHAR2(100) NOT NULL,
    currency   VARCHAR2(3)   NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    CONSTRAINT uq_asset_user_type_symbol UNIQUE (user_id, type, symbol),
    CONSTRAINT ck_asset_type CHECK (type IN ('BIST_STOCK', 'US_STOCK', 'FUND', 'CURRENCY', 'GOLD'))
);

CREATE TABLE investment_transaction (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     NUMBER       NOT NULL REFERENCES app_user (id),
    asset_id    NUMBER       NOT NULL REFERENCES asset (id),
    type        VARCHAR2(10) NOT NULL,
    trade_date  DATE         NOT NULL,
    quantity    NUMBER(19,8) NOT NULL,
    unit_price  NUMBER(19,8) NOT NULL,
    commission  NUMBER(19,4) DEFAULT 0 NOT NULL,
    currency    VARCHAR2(3)  NOT NULL,
    fx_rate_try NUMBER(19,8),
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT ck_inv_tx_type CHECK (type IN ('BUY', 'SELL')),
    CONSTRAINT ck_inv_tx_quantity CHECK (quantity > 0),
    CONSTRAINT ck_inv_tx_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_inv_tx_commission CHECK (commission >= 0)
);

CREATE INDEX ix_inv_tx_asset_date ON investment_transaction (asset_id, trade_date, id);
